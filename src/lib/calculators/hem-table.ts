function incomeBandIndex(grossAnnualIncome: number): number {
  for (let i = 0; i < INCOME_THRESHOLDS.length; i++) {
    if (grossAnnualIncome <= INCOME_THRESHOLDS[i]) return i;
  }
  return INCOME_THRESHOLDS.length;
}

/** Real HEM monthly benchmark for a household. `dependents` is clamped to the table's 0-10 range. */
export function getHemMonthly(isJoint: boolean, dependents: number, grossAnnualIncome: number): number {
  const clampedDependents = Math.max(0, Math.min(10, Math.round(dependents)));
  const code = `${isJoint ? "C" : "S"}${clampedDependents}`;
  const row = HEM_MONTHLY[code] ?? HEM_MONTHLY[isJoint ? "C0" : "S0"];
  const band = incomeBandIndex(Math.max(0, grossAnnualIncome));
  return row[band];
}
